#!/usr/bin/env node
/**
 * Builds the skill's self-contained CLI and regenerates the reference docs from an Atrium checkout,
 * so the validator and the component catalogue always match the platform version you deploy to.
 *
 *   ATRIUM_ROOT=~/personal/atrium-contabo node tools/build.mjs
 *
 * Outputs (commit them — the skill must work without Atrium or npm installed):
 *   skills/atriumify/scripts/atrium-bundle.mjs
 *   skills/atriumify/references/components.md
 *   skills/atriumify/references/schemas.md
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..');
const atrium = path.resolve((process.env.ATRIUM_ROOT ?? '').replace(/^~(?=\/)/, process.env.HOME ?? '~'));
if (!process.env.ATRIUM_ROOT) {
  console.error('Set ATRIUM_ROOT to an Atrium checkout with dependencies installed (pnpm install).');
  process.exit(1);
}
const hoisted = path.join(atrium, 'node_modules/.pnpm/node_modules');
const esbuild = createRequire(path.join(hoisted, 'noop.js'))('esbuild');

const pkg = (name, entry = 'src/index.ts') => path.join(atrium, 'packages', name, entry);
const common = {
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  nodePaths: [hoisted],
  alias: {
    '@atrium/schema': pkg('schema'),
    '@atrium/animations': pkg('animations'),
    '@atrium/component-registry': pkg('component-registry'),
    '@atrium/design-tokens': pkg('design-tokens'),
    '@atrium/templates': pkg('templates'),
    '@atrium/exporter/zip': pkg('exporter', 'src/zip.ts'),
    '@atrium/exporter/bundle': pkg('exporter', 'src/bundle.ts'),
    '@atrium/builder-core/normalize': pkg('builder-core', 'src/normalize.ts'),
    '@atrium/renderer-core/icons-data': pkg('renderer-core', 'src/ui/icons-data.ts'),
    '@atrium/renderer-core/styles': pkg('renderer-core', 'src/styles.tsx'),
  },
  // jszip pulls in a CommonJS build; give it a `require` inside the ESM bundle.
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  legalComments: 'none',
  logLevel: 'warning',
};

const atriumCommit = execFileSync('git', ['-C', atrium, 'rev-parse', '--short', 'HEAD']).toString().trim();

// Class names the renderer can output (static literals in its components), for the CSS typo check.
const sourceClasses = new Set();
const scan = (dir) => {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) scan(full);
    else if (/\.(tsx?|ts)$/.test(e.name)) {
      const src = readFileSync(full, 'utf8');
      for (const m of src.matchAll(/\ba-[a-z0-9]+(?:[_-][a-z0-9]+)*(?:__[a-z0-9-]+)?(?:--[a-z0-9-]+)?/g)) sourceClasses.add(m[0]);
      // Template modifiers with a fallback, e.g. `a-icon-badge--${style ?? 'plain'}` → a-icon-badge--plain.
      for (const m of src.matchAll(/\b(a-[a-z0-9_-]+--)\$\{[^}]*?(?:\?\?|\|\|)\s*'([a-z0-9-]+)'\s*\}/g)) sourceClasses.add(m[1] + m[2]);
    }
  }
};
scan(pkg('renderer-core', 'src'));
const skill = path.join(repo, 'skills/atriumify');

await esbuild.build({
  ...common,
  entryPoints: [path.join(here, 'src/cli.ts')],
  outfile: path.join(skill, 'scripts/atrium-bundle.mjs'),
  minify: true,
  define: { __ATRIUM_COMMIT__: JSON.stringify(atriumCommit), __RENDERER_SOURCE_CLASSES__: JSON.stringify([...sourceClasses].sort()) },
  banner: { js: `#!/usr/bin/env node\n// atrium-bundle — generated by tools/build.mjs from Atrium ${atriumCommit}. Do not edit.\n${common.banner.js}` },
});

const tmp = mkdtempSync(path.join(tmpdir(), 'atrium-skill-'));
try {
  const gen = path.join(tmp, 'gen.mjs');
  await esbuild.build({ ...common, entryPoints: [path.join(here, 'src/gen-reference.ts')], outfile: gen });
  execFileSync(process.execPath, [gen, path.join(skill, 'references'), atriumCommit, pkg('renderer-core', 'src/ui/icon.tsx')], { stdio: 'inherit' });
  const example = path.join(tmp, 'example.mjs');
  await esbuild.build({ ...common, entryPoints: [path.join(here, 'src/gen-example.ts')], outfile: example });
  execFileSync(process.execPath, [example, path.join(skill, 'examples')], { stdio: 'inherit' });
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
console.log(`Built from Atrium ${atriumCommit}.`);
